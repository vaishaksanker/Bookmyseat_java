-- BookMyShow schema. Portable between PostgreSQL and H2 (MODE=PostgreSQL).
-- Every statement is idempotent so it can run on each application start.

CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(255)  NOT NULL UNIQUE,
    password_hash VARCHAR(255)  NOT NULL,
    role          VARCHAR(20)   NOT NULL,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS venues (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(150) NOT NULL,
    address        VARCHAR(255),
    city           VARCHAR(100),
    total_capacity INTEGER      NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200)  NOT NULL,
    description     VARCHAR(2000),
    category        VARCHAR(50),
    venue_id        INTEGER       NOT NULL REFERENCES venues(id),
    organizer_id    INTEGER       NOT NULL REFERENCES users(id),
    event_date_time TIMESTAMP     NOT NULL,
    end_date_time   TIMESTAMP,
    ticket_price    NUMERIC(10,2) NOT NULL,
    total_seats     INTEGER       NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS seats (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id    INTEGER     NOT NULL REFERENCES venues(id),
    event_id    INTEGER     NOT NULL REFERENCES events(id),
    seat_row    VARCHAR(5)  NOT NULL,
    seat_number INTEGER     NOT NULL,
    seat_label  VARCHAR(10) NOT NULL,
    status      VARCHAR(20) NOT NULL,
    CONSTRAINT uq_event_seat_label UNIQUE (event_id, seat_label)
);

CREATE TABLE IF NOT EXISTS bookings (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER       NOT NULL REFERENCES users(id),
    event_id     INTEGER       NOT NULL REFERENCES events(id),
    status       VARCHAR(20)   NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL,
    booking_time TIMESTAMP     NOT NULL
);

-- A seat can be booked again after a cancellation, so uniqueness is per booking.
-- Double-booking is prevented by SeatDAO.reserveSeats (row lock + conditional update).
CREATE TABLE IF NOT EXISTS booking_seats (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER     NOT NULL REFERENCES bookings(id),
    seat_id    INTEGER     NOT NULL REFERENCES seats(id),
    seat_label VARCHAR(10) NOT NULL,
    CONSTRAINT uq_booking_seat UNIQUE (booking_id, seat_id)
);

CREATE TABLE IF NOT EXISTS payments (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id            INTEGER       NOT NULL UNIQUE REFERENCES bookings(id),
    amount                NUMERIC(10,2) NOT NULL,
    status                VARCHAR(20)   NOT NULL,
    transaction_reference VARCHAR(50),
    failure_reason        VARCHAR(255),
    payment_time          TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS tickets (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number   VARCHAR(40)   NOT NULL UNIQUE,
    booking_id      INTEGER       NOT NULL UNIQUE REFERENCES bookings(id),
    user_id         INTEGER       NOT NULL REFERENCES users(id),
    event_id        INTEGER       NOT NULL REFERENCES events(id),
    customer_name   VARCHAR(100),
    event_name      VARCHAR(200),
    venue_name      VARCHAR(150),
    event_date_time TIMESTAMP,
    seat_labels     VARCHAR(2000),
    total_amount    NUMERIC(10,2),
    payment_status  VARCHAR(20),
    generated_at    TIMESTAMP     NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_seats_event ON seats(event_id);
CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings(user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_event ON bookings(event_id);
CREATE INDEX IF NOT EXISTS idx_booking_seats_booking ON booking_seats(booking_id);
